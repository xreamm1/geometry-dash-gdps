CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  username TEXT NOT NULL COLLATE NOCASE UNIQUE,
  password_hash TEXT NOT NULL,
  password_salt TEXT NOT NULL,
  created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS levels (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  level_string TEXT NOT NULL,
  creator_id INTEGER NOT NULL REFERENCES users(id),
  version INTEGER NOT NULL DEFAULT 1,
  length INTEGER NOT NULL DEFAULT 0,
  difficulty INTEGER NOT NULL DEFAULT 0,
  stars INTEGER NOT NULL DEFAULT 0,
  demon INTEGER NOT NULL DEFAULT 0,
  demon_difficulty INTEGER NOT NULL DEFAULT 0,
  auto INTEGER NOT NULL DEFAULT 0,
  two_player INTEGER NOT NULL DEFAULT 0,
  object_count INTEGER NOT NULL DEFAULT 0,
  song_id INTEGER NOT NULL DEFAULT 0,
  audio_track INTEGER NOT NULL DEFAULT 0,
  coins INTEGER NOT NULL DEFAULT 0,
  verified_coins INTEGER NOT NULL DEFAULT 0,
  copy_password TEXT NOT NULL DEFAULT '0',
  downloads INTEGER NOT NULL DEFAULT 0,
  likes INTEGER NOT NULL DEFAULT 0,
  featured INTEGER NOT NULL DEFAULT 0,
  epic INTEGER NOT NULL DEFAULT 0,
  ldm INTEGER NOT NULL DEFAULT 0,
  original_id INTEGER NOT NULL DEFAULT 0,
  uploaded_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS levels_recent ON levels(uploaded_at DESC);
CREATE INDEX IF NOT EXISTS levels_creator ON levels(creator_id, uploaded_at DESC);
CREATE INDEX IF NOT EXISTS levels_name ON levels(name COLLATE NOCASE);

CREATE TABLE IF NOT EXISTS rate_limits (
  key_hash TEXT PRIMARY KEY,
  window_start INTEGER NOT NULL,
  request_count INTEGER NOT NULL
);

